// SQLSync is how the copies of one replicated `sql` database reach each other.
//
// The database engine (pkg/database/engines/sql/distributed) keeps each
// database in musql, whose replication layer converges copies by anti-entropy:
// exchange version vectors, pull the ops a peer is missing, exchange
// acknowledgements so the op log can be pruned, and bootstrap from a snapshot
// when what is missing has been pruned. These four calls are that, and nothing
// else; a write's low-latency delivery is a pubsub message (Push), not an RPC.
//
// ONE SERVICE PER NODE, FOR EVERY DATABASE IT HOLDS. Every request names its
// database, so one handler answers for all of them; a protocol per database
// would be a stream handler per database on one host.

