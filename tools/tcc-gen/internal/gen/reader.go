// reader.go renders a typed reader over a COMPILED object, from the locations
// the vocabulary declares.
//
// It is the half the flat models could not do. An editor wants a form over
// authored config; a runtime has the object and wants the value, and the two
// part exactly where a matcher captures a branch — which is why this renders
// from Located and not from Field.

// RenderReaders emits one file holding a reader for every kind.
//
// THE ACCESSOR IS NOT GENERATED AND THE FIELDS ARE. `r.String("a","b")` is map
// descent and knows no vocabulary; which path to descend is the vocabulary and
// nothing else, so that is the half that comes from here.
//
// WHAT A KIND READS AS is in model.go: its own fields, a block per key prefix,
// a typed entry per nested group, presence for every number and flag that may
// be absent, and the constants a consumer would otherwise spell by hand.
func RenderReaders(pkg string, root []*engine.Node, kinds []string) []byte {
	m := buildModel(root, kinds, reservedNames(pkg))

	var body bytes.Buffer
	body.Write(m.renderKindNames())
	for _, t := range m.order {
		body.Write(t.render())
		body.WriteString("\n")
	}

	// EVERY READER, BY KIND. A consumer that walks a project meets resources by
	// kind at runtime and cannot name a type per branch; and a test can exercise
	// what the generator emitted for every kind rather than for the handful
	// somebody remembered to call.
	body.WriteString("// Readers is every kind's reader, by the kind's own name.\n")
	body.WriteString("var Readers = map[string]func(Resource) any{\n")
	for _, kind := range m.kinds {
		fmt.Fprintf(&body, "\t%q: func(r Resource) any { return Read%s(r) },\n", kind, goIdent(kind))
	}
	body.WriteString("}\n\n")

	// THE CROSS-KIND QUESTIONS. What a project builds and where its content
	// comes from are asked of every resource rather than of one kind, so they
	// get the union of what any kind declares under those keys.
	//
	// WorkloadBlock is the third such question: what a tier needs of whatever
	// it runs. `execution` is a call and a timeout on a function and a cpu on an
	// application, so no kind's own type answers it for every kind, and a
	// resolver that knows only "something runnable" would otherwise spell the
	// paths back out of the vocabulary.
	for _, union := range []struct {
		name string
		keys []string
	}{
		{"SourceBlock", []string{"source"}},
		{"BuildBlock", []string{"build"}},
		{"WorkloadBlock", []string{"egress", "execution", "implements", "limits", "ports", "runtime", "serve", "variables"}},
	} {
		body.Write(RenderUnion(union.name, root, kinds, union.keys, m.groupsUnder(union.keys)))
		body.WriteString("\n")
	}

	body.WriteString(presentHelper)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tcc-gen. DO NOT EDIT.\n//\n")
	fmt.Fprintf(&b, "// A typed view of every kind, as it sits in a COMPILED object.\n//\n")
	fmt.Fprintf(&b, "// EVERY PATH HERE IS THE COMPILED KEY, which is not always where the value was\n")
	fmt.Fprintf(&b, "// written: a field under a captured branch compiles somewhere else, and the\n")
	fmt.Fprintf(&b, "// comment on it says where it came from. That distinction is the reason these\n")
	fmt.Fprintf(&b, "// are generated rather than written by hand - it is invisible in the yaml and\n")
	fmt.Fprintf(&b, "// a reader that guesses reads the wrong place and reports nothing.\n//\n")
	fmt.Fprintf(&b, "// A NUMBER OR A FLAG THAT MAY BE ABSENT IS A POINTER, nil when the object does\n")
	fmt.Fprintf(&b, "// not carry it, because a quota of 0 is an answer and a missing quota is not.\n")
	fmt.Fprintf(&b, "// A string is not: a compiled object omits what was not written, so absent\n")
	fmt.Fprintf(&b, "// and empty are the same answer.\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	if bytes.Contains(body.Bytes(), []byte("time.Duration")) {
		fmt.Fprintf(&b, "import \"time\"\n\n")
	}

	// THE ACCESSOR IS THE CORE'S. These readers need map descent at a path —
	// String/Strings/Int/Float/Bool/Duration on a Resource — which is mechanism
	// rather than vocabulary, so it is rendered beside them by RenderCore and
	// not declared twice here.
	b.Write(body.Bytes())

	// FORMATTED HERE, because the drift check is byte-exact and a generator that
	// emitted unformatted source would fail it the moment anybody ran gofmt.
	out, err := format.Source(b.Bytes())
	if err != nil {
		return b.Bytes()
	}
	return out
}

const presentHelper = `// present is a value the object may not carry: nil when it does not.
func present[T any](v T, ok bool) *T {
	if !ok {
		return nil
	}
	return &v
}
`

func goTypeFor(read string) string {
	switch read {
	case "Strings":
		return "[]string"
	case "Bool":
		return "bool"
	case "Int":
		return "int64"
	case "Float":
		return "float64"
	case "Duration":
		return "time.Duration"
	default:
		return "string"
	}
}

// goIdent turns a compiled key into an exported Go name: object/versioning ->
// ObjectVersioning, so the field says where the value is without a tag.
func goIdent(path string) string {
	var out strings.Builder
	for _, part := range strings.FieldsFunc(path, func(r rune) bool { return r == '/' || r == '_' || r == '-' }) {
		if part == "" {
			continue
		}
		out.WriteString(strings.ToUpper(part[:1]))
		out.WriteString(part[1:])
	}
	return out.String()
}

// RenderUnion emits one reader over a key PREFIX, across every kind that
// declares anything under it.
//
// # Why a union and not a per-kind reader
//
// Some questions are asked of a project rather than of a kind: what does this
// build, what does it serve. `source/` and `build/` are declared on many kinds
// and not identically — a function has `source/git`, an application has
// `source/image`, only a container kind has `build/dockerfile` — so a caller
// walking every resource wants the union of what any of them can say.
//
// THE ALTERNATIVE WAS A HAND-WRITTEN UNION, and that is what this replaces: a
// struct listing every field somebody remembered, read at paths somebody
// remembered, which is wrong in both directions at once — it read
// build/dockerfile off kinds that have none, and it would have missed a field
// added to any kind.
func RenderUnion(name string, root []*engine.Node, kinds []string, prefixes []string, groups []unionGroup) []byte {
	under := map[string]bool{}
	for _, prefix := range prefixes {
		under[prefix] = true
	}
	seen := map[string]Located{}
	for _, kind := range kinds {
		for _, l := range Locations(root, kind) {
			if len(l.Key) == 0 || !under[l.Key[0]] {
				continue
			}
			// A FIELD DECLARED ON TWO KINDS IS ONE FIELD. It compiles at the
			// same key or it is not the same field, so the first wins and a
			// disagreement would be the vocabulary's to resolve, not this.
			if _, held := seen[l.Path()]; !held {
				seen[l.Path()] = l
			}
		}
	}

	at := make([]Located, 0, len(seen))
	for _, l := range seen {
		at = append(at, l)
	}
	sort.Slice(at, func(i, j int) bool { return at[i].Path() < at[j].Path() })

	quoted := make([]string, 0, len(prefixes))
	for _, prefix := range prefixes {
		quoted = append(quoted, fmt.Sprintf("%q", prefix))
	}

	var b bytes.Buffer
	if len(quoted) == 1 {
		fmt.Fprintf(&b, "// %s is every field any kind declares under %s, read from a compiled\n", name, quoted[0])
		fmt.Fprintf(&b, "// object. A kind that declares none of them reads as the zero value.\n")
	} else {
		fmt.Fprintf(&b, "// %s is every field any kind declares under these keys, read from a\n", name)
		fmt.Fprintf(&b, "// compiled object: %s.\n", strings.Join(quoted, ", "))
		fmt.Fprintf(&b, "// A kind that declares none of them reads as the zero value.\n")
	}
	fmt.Fprintf(&b, "type %s struct {\n", name)
	type line struct{ name, text string }
	var lines []line
	for _, l := range at {
		note := ""
		if strings.Join(l.Key, "/") != strings.Join(l.Authored, "/") {
			note = "  // authored at " + strings.Join(l.Authored, "/")
		}
		if l.Captures {
			note = "  // which of " + strings.Join(l.Branch, ", ") + " was written"
		}
		lines = append(lines, line{goIdent(l.Path()), fmt.Sprintf("\t%s %s%s\n", goIdent(l.Path()), fieldType(l), note)})
	}
	for _, g := range groups {
		lines = append(lines, line{goIdent(g.key), fmt.Sprintf("\t%s %s\n", goIdent(g.key), g.goType())})
	}
	sort.Slice(lines, func(i, j int) bool { return lines[i].name < lines[j].name })
	for _, l := range lines {
		b.WriteString(l.text)
	}
	fmt.Fprintf(&b, "}\n\n")

	fmt.Fprintf(&b, "// Read%s decodes one from a resource.\nfunc Read%s(r Resource) %s {\n", name, name, name)
	fmt.Fprintf(&b, "\tvar out %s\n", name)
	reads := map[string]string{}
	for _, l := range at {
		call := callArgs(l.Key)
		switch {
		case optional(l):
			reads[goIdent(l.Path())] = fmt.Sprintf("\tout.%s = present[%s](r.%s(%s))\n", goIdent(l.Path()), goTypeFor(l.Read), l.Read, call)
		case scalarPair(l.Read):
			reads[goIdent(l.Path())] = fmt.Sprintf("\tout.%s, _ = r.%s(%s)\n", goIdent(l.Path()), l.Read, call)
		default:
			reads[goIdent(l.Path())] = fmt.Sprintf("\tout.%s = r.%s(%s)\n", goIdent(l.Path()), l.Read, call)
		}
	}
	for _, g := range groups {
		reads[goIdent(g.key)] = g.read()
	}
	for _, l := range lines {
		b.WriteString(reads[l.name])
	}
	fmt.Fprintf(&b, "\treturn out\n}\n")
	return b.Bytes()
}

// unionGroup is a nested group a union carries whole: `variables` on every kind
// that declares one, read into the one entry type they all share.
type unionGroup struct {
	key   string
	entry string
	list  bool
}

func (g unionGroup) goType() string {
	if g.list {
		return "[]" + g.entry
	}
	return "map[string]" + g.entry
}

func (g unionGroup) read() string {
	field, call := goIdent(g.key), fmt.Sprintf("%q", g.key)
	if g.list {
		return fmt.Sprintf("\tfor _, e := range r.List(%s) {\n\t\tout.%s = append(out.%s, Read%s(e))\n\t}\n", call, field, field, g.entry)
	}
	return fmt.Sprintf("\tfor _, name := range r.Keys(%s) {\n\t\tif out.%s == nil {\n\t\t\tout.%s = map[string]%s{}\n\t\t}\n\t\tout.%s[name] = Read%s(r.Sub(%s, name))\n\t}\n",
		call, field, field, g.entry, field, g.entry, call)
}

// groupsUnder is every nested group a kind declares at one of these keys, by
// the entry type it reads as.
//
// ONE TYPE OR NONE. A union field holds one Go type, so two kinds whose entries
// under the same key are different types cannot share it — and picking one
// would decode the other kind's entries into a struct missing its fields. That
// is the vocabulary's disagreement to resolve, so it stops the generator.
func (m *model) groupsUnder(keys []string) []unionGroup {
	under := map[string]bool{}
	for _, key := range keys {
		under[key] = true
	}
	found := map[string]unionGroup{}
	for _, t := range m.order {
		if t.role != "kind" {
			continue
		}
		for _, mem := range t.members {
			if mem.sub == nil || mem.sub.role != "entry" || len(mem.key) != 1 || !under[mem.key[0]] {
				continue
			}
			g := unionGroup{key: mem.key[0], entry: mem.sub.name, list: mem.sub.list}
			if held, ok := found[g.key]; ok && held != g {
				panic(fmt.Sprintf("tcc-gen: %q reads as %s on one kind and %s on another, so no union can carry it", g.key, held.entry, g.entry))
			}
			found[g.key] = g
		}
	}
	out := make([]unionGroup, 0, len(found))
	for _, g := range found {
		out = append(out, g)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].key < out[j].key })
	return out
}
