package gen

import (
	"bytes"
	"fmt"
	"strings"
)

// reader.go renders a typed reader over a COMPILED object, from the locations
// the vocabulary declares.
//
// It is the half the flat models could not do. An editor wants a form over
// authored config; a runtime has the object and wants the value, and the two
// part exactly where a matcher captures a branch — which is why this renders
// from Located and not from Field.

// RenderReader emits a reader for one kind.
func RenderReader(pkg, kind string, at []Located) []byte {
	var b bytes.Buffer

	title := goIdent(kind)
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	fmt.Fprintf(&b, "// Code generated by tcc-gen. DO NOT EDIT.\n//\n")
	fmt.Fprintf(&b, "// %s as it sits in a COMPILED object. Every path here is the vocabulary's\n", title)
	fmt.Fprintf(&b, "// own compiled key, which is not always where the value was written: a field\n")
	fmt.Fprintf(&b, "// under a captured branch compiles somewhere else, and the comment on it says\n")
	fmt.Fprintf(&b, "// where it came from.\n\n")

	fmt.Fprintf(&b, "type %s struct {\n", title)
	for _, l := range at {
		note := ""
		if strings.Join(l.Key, "/") != strings.Join(l.Authored, "/") {
			note = "  // authored at " + strings.Join(l.Authored, "/")
		}
		if l.Captures {
			note = "  // which of " + strings.Join(l.Branch, ", ") + " was written"
		}
		fmt.Fprintf(&b, "\t%s %s%s\n", goIdent(l.Path()), goTypeFor(l.Read), note)
	}
	fmt.Fprintf(&b, "}\n\n")

	fmt.Fprintf(&b, "// Read%s decodes one from a resource.\nfunc Read%s(r Resource) %s {\n", title, title, title)
	fmt.Fprintf(&b, "\tvar out %s\n", title)
	for _, l := range at {
		args := make([]string, 0, len(l.Key))
		for _, seg := range l.Key {
			args = append(args, fmt.Sprintf("%q", seg))
		}
		call := strings.Join(args, ", ")
		field := goIdent(l.Path())
		switch l.Read {
		case "Int", "Duration", "Float", "Bool":
			// THESE ANSWER (value, ok) BECAUSE ABSENT AND ZERO ARE DIFFERENT for
			// a number: a quota of 0 is an answer and a missing quota is not.
			fmt.Fprintf(&b, "\tout.%s, _ = r.%s(%s)\n", field, l.Read, call)
		default:
			fmt.Fprintf(&b, "\tout.%s = r.%s(%s)\n", field, l.Read, call)
		}
	}
	fmt.Fprintf(&b, "\treturn out\n}\n")
	return b.Bytes()
}

func goTypeFor(read string) string {
	switch read {
	case "Strings":
		return "[]string"
	case "Bool":
		return "bool"
	case "Int":
		return "int64"
	case "Float":
		return "float64"
	case "Duration":
		return "time.Duration"
	default:
		return "string"
	}
}

// goIdent turns a compiled key into an exported Go name: object/versioning ->
// ObjectVersioning, so the field says where the value is without a tag.
func goIdent(path string) string {
	var out strings.Builder
	for _, part := range strings.FieldsFunc(path, func(r rune) bool { return r == '/' || r == '_' || r == '-' }) {
		if part == "" {
			continue
		}
		out.WriteString(strings.ToUpper(part[:1]))
		out.WriteString(part[1:])
	}
	return out.String()
}
